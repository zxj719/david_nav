"""Deterministic Markdown documentation for aggregated parameter schemas."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, List, Union

from nav_bringup.navcfg.schema import ParameterCatalog, ParameterSpec

GENERATED_NOTICE = '<!-- Generated by navcfg doc; edit config/schema.yaml instead. -->'


def render_catalog(
    catalog: ParameterCatalog,
    title: str = 'Navigation parameters',
) -> str:
    """Render a parameter catalog as stable Markdown.

    Args:
        catalog: Aggregated package schemas.
        title: Document heading.

    Returns:
        Markdown ending in one newline.
    """
    lines = [
        f'# {title}',
        '',
        GENERATED_NOTICE,
        '',
        'This file lists every robot-profile key declared by package schemas.',
        '',
    ]
    for package in catalog.packages:
        specs = [spec for spec in catalog.specs if spec.package == package]
        lines.extend([f'## `{_cell(package)}`', ''])
        if not specs:
            lines.extend(['No parameters declared.', ''])
            continue
        lines.extend([
            '| Key | Type | Unit | Required / default | Constraints | Description | Tuning |',
            '|---|---|---|---|---|---|---|',
        ])
        lines.extend(_row(spec) for spec in specs)
        lines.append('')
    return '\n'.join(lines).rstrip() + '\n'


def write_catalog(
    path: Union[str, Path],
    catalog: ParameterCatalog,
    title: str = 'Navigation parameters',
) -> None:
    """Write generated parameter documentation.

    Args:
        path: Markdown output path; parent directories are created.
        catalog: Aggregated package schemas.
        title: Document heading.
    """
    output = Path(path)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(render_catalog(catalog, title), encoding='utf-8')


def _row(spec: ParameterSpec) -> str:
    cells = [
        f'`{spec.key}`',
        f'`{_type_name(spec)}`',
        spec.unit or '—',
        _requirement(spec),
        _constraints(spec),
        spec.description,
        f'[notes]({spec.tuning})' if spec.tuning else '—',
    ]
    return '| ' + ' | '.join(_cell(value) for value in cells) + ' |'


def _type_name(spec: ParameterSpec) -> str:
    if spec.value_type == 'list' and spec.items:
        return f'list[{spec.items}]'
    return spec.value_type


def _requirement(spec: ParameterSpec) -> str:
    if spec.required:
        return '**required**'
    if spec.has_default:
        return f'default: `{_value(spec.default)}`'
    return 'optional (unset)'


def _constraints(spec: ParameterSpec) -> str:
    constraints: List[str] = []
    if spec.value_range is not None:
        low, high = spec.value_range
        constraints.append(
            f'range: `{_bound(low, "-inf")} .. {_bound(high, "inf")}`')
    if spec.choices is not None:
        choices = ', '.join(f'`{_value(choice)}`' for choice in spec.choices)
        constraints.append(f'choices: {choices}')
    return '<br>'.join(constraints) or '—'


def _bound(value: Any, unbounded: str) -> str:
    return unbounded if value is None else _value(value)


def _value(value: Any) -> str:
    return json.dumps(
        value, ensure_ascii=False, sort_keys=True, separators=(',', ':'))


def _cell(value: str) -> str:
    return str(value).replace('\\', '\\\\').replace('|', '\\|').replace('\n', '<br>')
