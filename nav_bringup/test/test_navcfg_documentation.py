"""Tests for generated parameter documentation."""

from pathlib import Path

from nav_bringup.navcfg import cli, documentation, schema

PACKAGE_DIR = Path(__file__).resolve().parents[1]
REPOSITORY_ROOT = PACKAGE_DIR.parent
PARAMETER_DOC = REPOSITORY_ROOT / 'docs' / 'parameters.md'


def _catalog():
    data = {
        'schema_version': 1,
        'package': 'demo_pkg',
        'parameters': {
            'limits.max_vel_x': {
                'type': 'float',
                'unit': 'm/s',
                'range': [0.0, 1.0],
                'required': True,
                'description': 'Maximum speed.',
                'tuning': 'docs/tuning.md#speed',
            },
            'record.storage': {
                'type': 'string',
                'default': 'sqlite3',
                'choices': ['sqlite3'],
                'description': 'Storage | plugin.',
            },
            'topics': {
                'type': 'list',
                'items': 'string',
                'default': [],
                'description': 'Topics.',
            },
        },
    }
    return schema.ParameterCatalog([schema.parse_schema(data, 'schema.yaml')])


def test_render_catalog_documents_every_schema_field_deterministically():
    """The table includes types, units, defaults, limits, choices, links and escaping."""
    rendered = documentation.render_catalog(_catalog())

    assert rendered.startswith('# Navigation parameters\n\n<!-- Generated by navcfg doc;')
    assert '| `limits.max_vel_x` | `float` | m/s | **required** |' in rendered
    assert 'range: `0.0 .. 1.0`' in rendered
    assert 'default: `"sqlite3"`' in rendered
    assert 'choices: `"sqlite3"`' in rendered
    assert '`list[string]`' in rendered
    assert 'Storage \\| plugin.' in rendered
    assert '[notes](docs/tuning.md#speed)' in rendered
    assert rendered == documentation.render_catalog(_catalog())


def test_doc_command_writes_a_catalog_from_explicit_schemas(tmp_path, capsys):
    """The CLI accepts repeated schemas and creates the requested output directory."""
    schema_path = tmp_path / 'schema.yaml'
    schema_path.write_text(
        'schema_version: 1\n'
        'package: demo_pkg\n'
        'parameters:\n'
        '  robot.name:\n'
        '    type: string\n'
        '    required: true\n'
        '    description: Robot name.\n',
        encoding='utf-8',
    )
    output = tmp_path / 'nested' / 'parameters.md'

    status = cli.main([
        'doc', '--schema', str(schema_path), '--output', str(output)])

    assert status == 0
    assert '`robot.name`' in output.read_text(encoding='utf-8')
    assert str(output) in capsys.readouterr().out


def test_checked_in_parameter_document_is_in_sync():
    """The committed Markdown exactly matches all source-tree package schemas."""
    paths = schema.find_source_schemas(REPOSITORY_ROOT)
    expected = documentation.render_catalog(schema.load_catalog(paths))

    assert PARAMETER_DOC.read_text(encoding='utf-8') == expected
