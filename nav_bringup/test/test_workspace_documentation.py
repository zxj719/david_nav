"""Check current navigation guides, relative links and documented CLI syntax without execution."""

from pathlib import Path
import re
import shlex
from urllib.parse import unquote

import pytest

from nav_bringup.navcfg.cli import build_parser as configuration_parser
from nav_bringup.navrun.cli import build_parser as run_parser

SOURCE = Path(__file__).resolve().parents[2]
GUIDES = (
    'README.md', 'CLAUDE.md',
    'docs/architecture.md', 'docs/porting.md', 'docs/behavior_policy.md',
    'docs/events.md', 'docs/runbook.md',
)


@pytest.mark.parametrize('name', GUIDES)
def test_current_guides_exist_and_use_resolvable_relative_file_links(name):
    """Portable navigation documentation must not point at an old author's machine."""
    path = SOURCE / name
    contents = path.read_text()
    assert contents.startswith('# ')
    assert '/home/unitree/' not in contents
    for target in re.findall(r'\[[^\]\n]+\]\(([^)\s]+)\)', contents):
        if target.startswith(('https://', 'http://', '#')):
            continue
        target = unquote(target.split('#', 1)[0])
        assert not Path(target).is_absolute(), (name, target)
        assert (path.parent / target).exists(), (name, target)


def test_all_six_plan_documents_are_present_and_parameter_catalog_stays_generated():
    """Five guides complement, not overwrite, the schema-generated parameter reference."""
    for name in ('architecture', 'parameters', 'porting', 'behavior_policy', 'events', 'runbook'):
        assert (SOURCE / 'docs' / (name + '.md')).is_file()
    assert 'Generated by navcfg doc' in (SOURCE / 'docs/parameters.md').read_text()


@pytest.mark.parametrize('name', ['README.md', 'CLAUDE.md', 'docs/runbook.md', 'docs/porting.md'])
def test_documented_navrun_navcfg_commands_parse_without_starting_them(name, capsys):
    """Only argparse is used: no command handler, ROS context, host setting or process starts."""
    commands = []
    for block in re.findall(r'```bash\n(.*?)```', (SOURCE / name).read_text(), re.DOTALL):
        for line in block.replace('\\\n', ' ').splitlines():
            words = shlex.split(line, comments=True)
            if not words or words[0] not in ('navrun', 'navcfg'):
                continue
            parser = run_parser() if words[0] == 'navrun' else configuration_parser()
            if '--help' in words:
                with pytest.raises(SystemExit) as result:
                    parser.parse_args(words[1:])
                assert result.value.code == 0
            else:
                parser.parse_args(words[1:])
            commands.append(words)
    assert commands, 'Each operational guide needs at least one concrete validated CLI example'
    capsys.readouterr()


def test_onboarding_does_not_recommend_old_global_kills_pushes_or_domain_one():
    """Historical instructions must not masquerade as current autonomous permissions."""
    for name in ('CLAUDE.md',):
        contents = (SOURCE / name).read_text()
        for stale in ('统一 1', 'pre-flight 杀所有 RSP', '默认 push', 'commit + push',
                      'ros2 run lightning run_loc_online'):
            assert stale not in contents
    runbook = (SOURCE / 'docs/runbook.md').read_text()
    assert 'P7.A1' in runbook and 'P7.A2' in runbook and 'P3.5' in runbook
